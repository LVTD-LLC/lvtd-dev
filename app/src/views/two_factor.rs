//! Two-factor authentication: the settings page, the summary panel on
//! account settings, and the code prompt during sign-in.

use app_auth::two_factor::{RECOVERY_CODE_COUNT, Setup, Status};
use maud::{Markup, PreEscaped, html};

/// One rendering of `/settings/two-factor`.
pub struct View<'a> {
    /// The provider a passwordless account confirms with instead of a password
    /// (`google` or `github` feature).
    pub confirm_with: Option<&'a str>,
    pub status: &'a Status,
    /// The enrolment in progress: QR code, manual key and the confirm form.
    pub setup: Option<&'a Setup>,
    /// Codes generated by this request, shown exactly once.
    pub recovery_codes: Option<&'a [String]>,
    pub error: Option<&'a str>,
    pub notice: Option<&'a str>,
}

pub fn page(view: &View<'_>) -> Markup {
    html! {
        section class="page settings two-factor" {
            h1 { "Two-factor authentication" }
            p class="lede" { "Protect your account with a code from an authenticator app in addition to the way you sign in." }
            @if let Some(error) = view.error { p class="alert" role="alert" { (error) } }
            @if let Some(notice) = view.notice { p class="alert" role="status" { (notice) } }
            @if let Some(codes) = view.recovery_codes { (recovery_codes(codes)) }
            @match (view.setup, view.status) {
                (Some(setup), _) => (setup_panel(setup)),
                (None, Status::On { recovery_codes_left }) => (enabled_panel(*recovery_codes_left, view.confirm_with)),
                (None, _) => (off_panel(view.confirm_with)),
            }
            p class="muted small" { a href="/settings" { "Back to account settings" } }
        }
    }
}

/// The summary on `/settings`, linking here.
pub fn panel(status: &Status) -> Markup {
    html! {
        section class="panel" id="two-factor" aria-labelledby="two-factor-heading" {
            (super::settings::panel_head("two-factor-heading", "Two-factor authentication", "A code from an authenticator app as a second step when you sign in."))
            @match status {
                Status::On { recovery_codes_left } => {
                    p { strong { "On" } " " span class="badge" { "Authenticator app" } }
                    p class="muted" { "Signing in with your password" @if cfg!(feature = "social-login") { " or a sign-in provider" } " also asks for a code from your authenticator app. " (*recovery_codes_left) " of " (RECOVERY_CODE_COUNT) " recovery codes left." }
                }
                Status::Pending => {
                    p { strong { "Off" } }
                    p class="muted" { "Setup was started but not finished. Scan the QR code and enter a code to turn it on." }
                }
                Status::Off => {
                    p { strong { "Off" } }
                    p class="muted" { "Add a second step to sign-in: a six-digit code from an app such as 1Password, Google Authenticator or Authy. Passkeys already count as two factors." }
                }
            }
            a class="btn" href="/settings/two-factor" {
                @match status { Status::On { .. } => "Manage two-factor authentication", Status::Pending => "Finish setup", Status::Off => "Turn on two-factor authentication" }
            }
        }
    }
}

/// The password field, or for passwordless accounts the pointer to confirming with their provider.
fn confirmation(confirm_with: Option<&str>) -> Markup {
    html! {
        @if let Some(provider) = confirm_with { (super::settings::confirmation_help(provider)) } @else {
            label { "Current password" input type="password" name="password" autocomplete="current-password" maxlength="256" required; }
        }
    }
}

fn off_panel(confirm_with: Option<&str>) -> Markup {
    html! {
        section class="panel" aria-labelledby="enable-heading" {
            h2 id="enable-heading" { "Turn on" }
            p class="muted" { "You will need an authenticator app on your phone or in your password manager. Confirm your identity to get a QR code to scan." }
            form class="form" method="post" action="/settings/two-factor" {
                input type="hidden" name="action" value="begin";
                (confirmation(confirm_with))
                button class="btn btn-primary" type="submit" { "Continue" }
            }
        }
    }
}

fn setup_panel(setup: &Setup) -> Markup {
    html! {
        section class="panel" aria-labelledby="scan-heading" {
            h2 id="scan-heading" { "1. Scan the QR code" }
            p class="muted" { "Open your authenticator app, add an account and scan this code." }
            div class="qr" { (PreEscaped(&setup.qr_svg)) }
            details {
                summary { "Can’t scan it? Enter the key manually" }
                p class="muted small" { "Choose “enter a setup key” in your app and type this key. It is a time-based code with six digits." }
                p class="manual-key" { code { (setup.manual_key) } }
                p class="muted small" { "On a phone, this link opens the app directly: " a href=(setup.otpauth_url) { "add to authenticator" } "." }
            }
        }
        section class="panel" aria-labelledby="confirm-heading" {
            h2 id="confirm-heading" { "2. Enter the code the app shows" }
            form class="form" method="post" action="/settings/two-factor" {
                input type="hidden" name="action" value="confirm";
                label for="code" { "Six-digit code" }
                input id="code" name="code" type="text" inputmode="numeric" pattern="[0-9 ]*" required minlength="6" maxlength="7" autocomplete="one-time-code" spellcheck="false" autofocus;
                button class="btn btn-primary" type="submit" { "Turn on two-factor authentication" }
            }
            form class="form" method="post" action="/settings/two-factor" {
                input type="hidden" name="action" value="cancel";
                button class="btn" type="submit" { "Cancel setup" }
            }
        }
    }
}

fn enabled_panel(recovery_codes_left: i64, confirm_with: Option<&str>) -> Markup {
    html! {
        section class="panel" aria-labelledby="status-heading" {
            h2 id="status-heading" { "On" }
            p class="muted" { "Signing in with your password" @if cfg!(feature = "social-login") { " or a sign-in provider" } " asks for a code from your authenticator app. Signing in with a passkey does not, because a passkey is already two factors." }
        }
        section class="panel" aria-labelledby="recovery-heading" {
            h2 id="recovery-heading" { "Recovery codes" }
            p class="muted" { "Each recovery code signs you in once if you lose your authenticator. You have " (recovery_codes_left) " of " (RECOVERY_CODE_COUNT) " left. Generating new codes replaces all of the old ones." }
            form class="form" method="post" action="/settings/two-factor" {
                input type="hidden" name="action" value="recovery_codes";
                (confirmation(confirm_with))
                button class="btn" type="submit" { "Generate new recovery codes" }
            }
        }
        section class="panel settings-danger" aria-labelledby="disable-heading" {
            h2 id="disable-heading" { "Turn off" }
            p class="muted" { "Signing in will no longer ask for an authenticator code. The authenticator entry and your recovery codes stop working." }
            form class="form" method="post" action="/settings/two-factor" {
                input type="hidden" name="action" value="disable";
                (confirmation(confirm_with))
                button class="btn btn-danger" type="submit" { "Turn off two-factor authentication" }
            }
        }
    }
}

/// Shown once, right after enrolment or regeneration; the codes are not stored.
fn recovery_codes(codes: &[String]) -> Markup {
    html! {
        div class="api-key-reveal" role="status" {
            p { strong { "Save these recovery codes now. They will not be shown again." } }
            p class="muted small" { "Keep them somewhere safe, such as your password manager. Each code works once, in place of an authenticator code." }
            ul class="recovery-codes" { @for code in codes { li { code { (code) } } } }
        }
    }
}

/// The step between password and session on `/sign-in/two-factor`.
pub fn challenge(error: Option<&str>) -> Markup {
    html! {
        section class="page auth-page two-factor" {
            div class="auth-card" {
                header class="auth-head" {
                    h1 { "Enter your code" }
                    p class="muted" { "Open your authenticator app and enter the six-digit code for this account. Lost the app? Enter one of your recovery codes instead." }
                }
                @if let Some(error) = error { p role="alert" class="alert" { (error) } }
                form class="form auth-form" method="post" action="/sign-in/two-factor" {
                    label for="code" { "Authenticator or recovery code" }
                    input id="code" name="code" type="text" required maxlength="16" autocomplete="one-time-code" autocapitalize="off" spellcheck="false" autofocus;
                    button class="btn btn-primary btn-block" type="submit" { "Sign in" }
                }
            }
            p class="muted small auth-switch" { "Wrong account? " a href="/sign-in" { "Start over" } }
        }
    }
}
